def ensure_physical_activities(activities: list, target: int = 2000) -> list:
    """Append physical-category activities until the pool holds `target` of them.

    Existing rows are preserved; new rows use deterministic PHYxxxx codes so
    re-seeding is stable. Rows match the 13-column activity schema:
    (code, he, en, category, subcat, strengthens, contras, min_cap, dur,
     gmin, gmax, location, desc).
    """
    out = list(activities)
    phys_count = sum(1 for r in out if len(r) > 3 and r[3] == "physical")
    counter = 1
    for base in PHYS_BASES:
        b_he, b_en, subcat, strengthens, min_cap, dur, gmin, gmax, loc = base
        for mod_he, mod_en in PHYS_MODIFIERS:
            for mult in PHYS_DURATION_MULT:
                if phys_count >= target:
                    return out
                code = f"PHY{counter:04d}"
                counter += 1
                new_dur = max(10, int(dur * mult))
                out.append((
                    code,
                    f"{b_he} - {mod_he}",
                    f"{b_en} - {mod_en}",
                    "physical",
                    subcat,
                    strengthens,
                    "",
                    min_cap,
                    new_dur,
                    gmin,
                    gmax,
                    loc,
                    b_he,
                ))
                phys_count += 1
    return out


