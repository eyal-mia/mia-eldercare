def expand_exercises(core: list) -> list:
    out = list(core)
    counter = 100
    for base in EXERCISE_BASES:
        (b_he, b_en, b_ru, typ, muscles, systems, strengthens, contras,
         intensity, min_cap, dur, reps, position, equip, desc) = base
        for mod_he, mod_en in EX_INTENSITY_VARIANTS:
            code = f"EX{counter:03d}"
            counter += 1
            out.append((
                code,
                f"{b_he} - {mod_he}",
                f"{b_en} - {mod_en}",
                f"{b_ru} - {mod_en}",
                typ, muscles, systems,
                strengthens, contras,
                intensity, min_cap, dur, reps, position, equip, desc,
            ))
            if len(out) >= 1000:
                return out[:1000]
    return out[:1000]
